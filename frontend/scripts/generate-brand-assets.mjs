// Node 22.18+ reads these data-only TypeScript modules without a build step.
import { readFile, writeFile } from "node:fs/promises"
import sharp from "sharp"
import { WORDMARK_ARC as arc, WORDMARK_GEOMETRY as mark } from "../src/lib/brand-mark.ts"
import { tokens } from "../src/lib/design-tokens.ts"

const { ink, paper } = tokens.color
const check = process.argv.includes("--check")

function symbol({ normalized = true } = {}) {
  // Raster SVG readers do not all support pathLength. Physical lengths describe
  // exactly the same arc when rendering PNGs through libvips.
  const length = normalized ? 1 : 2 * Math.PI * mark.radius
  return `<circle cx="${mark.center}" cy="${mark.center}" r="${mark.radius}" fill="none" stroke="currentColor" stroke-width="${mark.strokeWidth}" stroke-linecap="${mark.linecap}"${normalized ? ' pathLength="1"' : ""} stroke-dasharray="${arc.dash * length} ${arc.gap * length}" stroke-dashoffset="${-arc.gap / 2 * length}" transform="${mark.rotation}"/>
  <circle cx="${mark.center}" cy="${mark.center}" r="${mark.dotRadius}" fill="currentColor"/>`
}

function adaptiveSvg(size) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${mark.viewBox}" width="${size}" height="${size}" role="img" aria-labelledby="title">
  <!-- Generated by npm run brand:generate from the Wordmark geometry and design tokens. -->
  <title id="title">Planora</title>
  <style>
    :root { color: ${ink}; }
    @media (prefers-color-scheme: dark) { :root { color: ${paper}; } }
  </style>
  ${symbol()}
</svg>
`
}

// One paper tile for all PNG consumers. The unchanged 24-unit mark is centred
// inside 32 units, keeping its outer edge inside Android's maskable safe zone.
const tile = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32" width="512" height="512" color="${ink}">
  <rect width="32" height="32" fill="${paper}"/>
  <g transform="translate(4 4)">${symbol({ normalized: false })}</g>
</svg>`

const assets = new Map([
  ["../public/favicon.svg", Buffer.from(adaptiveSvg(32))],
  ["../../docs/assets/logo.svg", Buffer.from(adaptiveSvg(96))],
])
for (const [name, size] of [["icon-32.png", 32], ["apple-touch-icon.png", 180], ["icon-192.png", 192], ["icon-512.png", 512]]) {
  assets.set(`../public/${name}`, await sharp(Buffer.from(tile)).resize(size, size).png().toBuffer())
}

let stale = false
for (const [relativePath, content] of assets) {
  const target = new URL(relativePath, import.meta.url)
  if (check) {
    const existing = await readFile(target).catch(() => null)
    if (!existing?.equals(content)) {
      console.error(`Stale brand asset: ${relativePath}. Run npm run brand:generate.`)
      stale = true
    }
  } else {
    await writeFile(target, content)
    console.log(`Generated ${relativePath}`)
  }
}
if (stale) process.exitCode = 1
